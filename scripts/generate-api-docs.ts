/**
 * Generates the OpenAPI description from the contracts in src/lib/contracts,
 * split into one file per domain so each can be read, reviewed and extended
 * on its own:
 *
 *   api/openapi/openapi.yaml                     entry point, references the domain files
 *   api/openapi/<domain>.yaml                    paths of one domain
 *   api/openapi/components/schemas/*.yaml        shared schemas
 *   api/openapi/components/responses/errors.yaml shared error responses
 *   api/openapi/README.md                        index
 *
 *   npm run contract:docs              write the files
 *   npm run contract:docs -- --check   exit 1 when they are out of date
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { stringify } from 'yaml';
import { z } from 'zod';
import { domains, ErrorResponse, IDEMPOTENCY_HEADER, type ApiContract, type ContractAuth } from '../src/lib/contracts';

type Json = Record<string, unknown>;

export const OUT_DIR = 'api/openapi';
const VERSION = '1.0.0';
const TITLE = 'IceFlow API — Nhà máy đá tinh khiết Rubi';
const GENERATED = 'Generated by `npm run contract:docs` from src/lib/contracts. Do not edit by hand.';

const ERROR_RESPONSES: Record<number, { name: string; description: string }> = {
  400: { name: 'BadRequest', description: 'Invalid request' },
  401: { name: 'Unauthorized', description: 'Not signed in or session expired' },
  403: {
    name: 'Forbidden',
    description: 'Not allowed for this role, or a password change is required (code PASSWORD_CHANGE_REQUIRED)',
  },
  404: { name: 'NotFound', description: 'Not found' },
  405: { name: 'MethodNotAllowed', description: 'Not supported' },
  409: {
    name: 'Conflict',
    description: 'Conflict with the current state (codes PAYROLL_LOCKED, SHIFT_FULL, PENDING_SHIFTS)',
  },
  422: {
    name: 'UnprocessableEntity',
    description: 'The Idempotency-Key was already used for a different request (code IDEMPOTENCY_KEY_REUSED)',
  },
  429: { name: 'TooManyRequests', description: 'Too many requests' },
  500: { name: 'ServerError', description: 'Server error' },
  503: { name: 'ServiceUnavailable', description: 'Service unavailable' },
};

/** Shared schemas collected while converting, keyed by their contract id. */
const shared: Record<string, Json> = {};

/** Where a shared schema lives, relative to api/openapi/. */
const sharedFile = (name: string) =>
  name === 'Error'
    ? 'components/schemas/error.yaml'
    : name === 'PaginationMeta'
      ? 'components/schemas/pagination.yaml'
      : 'components/schemas/common.yaml';

function rewriteRefs(node: unknown, refFor: (name: string) => string): unknown {
  if (Array.isArray(node)) return node.map((item) => rewriteRefs(item, refFor));
  if (node && typeof node === 'object') {
    return Object.fromEntries(
      Object.entries(node as Json)
        // Zod states the safe-integer range on every integer; it is noise in the docs.
        .filter(([key, value]) => !((key === 'maximum' || key === 'minimum') && Math.abs(value as number) === Number.MAX_SAFE_INTEGER))
        .map(([key, value]) =>
        key === '$ref' && typeof value === 'string' && value.startsWith('#/$defs/')
          ? [key, refFor(value.slice('#/$defs/'.length))]
          : [key, rewriteRefs(value, refFor)]
      )
    );
  }
  return node;
}

/** Converts a Zod schema, registering shared schemas and pointing `$ref`s at their files. */
function toSchema(schema: z.ZodType, fromDir = ''): Json {
  const { $schema: _draft, $defs, ...rest } = z.toJSONSchema(schema, { unrepresentable: 'any' }) as Json;
  for (const [name, definition] of Object.entries(($defs ?? {}) as Record<string, Json>)) {
    const { id: _id, ...body } = definition;
    // Inside a shared file, sibling schemas are referenced locally.
    shared[name] = rewriteRefs(body, (target) =>
      sharedFile(target) === sharedFile(name) ? `#/${target}` : `./${sharedFile(target).split('/').pop()}#/${target}`
    ) as Json;
  }
  return rewriteRefs(rest, (name) => `${fromDir}./${sharedFile(name)}#/${name}`) as Json;
}

export function describeAuth(auth: ContractAuth): string {
  switch (auth.kind) {
    case 'public':
      return 'Public';
    case 'session':
      return 'Any signed-in user';
    case 'roles':
      return auth.roles.join(', ');
    case 'custom':
      return auth.description;
  }
}

function parameters(contract: ApiContract): Json[] {
  const list: Json[] = [];
  for (const [location, schema] of [['path', contract.params], ['query', contract.query]] as const) {
    if (!schema) continue;
    for (const [name, field] of Object.entries(schema.shape)) {
      list.push({
        name,
        in: location,
        required: location === 'path' || !(field as z.ZodType).safeParse(undefined).success,
        schema: toSchema(field as z.ZodType),
      });
    }
  }
  if (contract.idempotent) {
    list.push({
      name: IDEMPOTENCY_HEADER,
      in: 'header',
      required: false,
      description:
        'One random value (a UUID) per submission, reused when that submission is resent. ' +
        'A resend is not written again and gets the first answer.',
      schema: { type: 'string', minLength: 1, maxLength: 100 },
    });
  }
  return list;
}

function operation(contract: ApiContract): Json {
  const responses: Json = {};
  const success = toSchema(contract.response);
  if (!('not' in success)) {
    responses[String(contract.successStatus ?? 200)] = {
      description: 'Success',
      content: { 'application/json': { schema: success } },
    };
  }
  for (const status of contract.errors) {
    responses[String(status)] = { $ref: `./components/responses/errors.yaml#/${ERROR_RESPONSES[status].name}` };
  }

  const result: Json = {
    operationId: contract.id,
    tags: [contract.tag],
    summary: contract.summary,
    description: [`Access: ${describeAuth(contract.auth)}.`, contract.notes].filter(Boolean).join('\n\n'),
  };
  if (contract.auth.kind === 'public') result.security = [];
  const params = parameters(contract);
  if (params.length > 0) result.parameters = params;
  if (contract.body) {
    result.requestBody = {
      required: !contract.body.safeParse(undefined).success,
      content: { 'application/json': { schema: toSchema(contract.body) } },
    };
  }
  result.responses = responses;
  return result;
}

/** JSON Pointer escaping of a path used inside a `$ref`. */
const pointer = (path: string) => path.replace(/~/g, '~0').replace(/\//g, '~1');

const yaml = (value: unknown, source?: string) =>
  `# ${GENERATED}${source ? `\n# Source: ${source}` : ''}\n` + stringify(value, { lineWidth: 0, aliasDuplicateObjects: false });

export function renderAll(): Record<string, string> {
  for (const key of Object.keys(shared)) delete shared[key];
  const files: Record<string, string> = {};
  const rootPaths: Json = {};
  const tags: Json[] = [];

  for (const domain of domains) {
    const paths: Record<string, Json> = {};
    for (const contract of domain.contracts) {
      (paths[contract.path] ??= {})[contract.method.toLowerCase()] = operation(contract);
      rootPaths[contract.path] = { $ref: `./${domain.file}.yaml#/paths/${pointer(contract.path)}` };
    }
    for (const tag of new Set(domain.contracts.map((contract) => contract.tag))) {
      tags.push({ name: tag, description: domain.description });
    }
    files[`${OUT_DIR}/${domain.file}.yaml`] = yaml(
      { openapi: '3.1.0', info: { title: `${TITLE}: ${domain.description}`, version: VERSION }, paths },
      'src/lib/contracts'
    );
  }

  const errorSchemaRef = { $ref: '../schemas/error.yaml#/Error' };
  // A schema converted on its own is emitted inline, so the shared Error body is built directly.
  const { $schema: _draft, id: _id, ...errorBody } = z.toJSONSchema(ErrorResponse, { unrepresentable: 'any' }) as Json;
  shared.Error = errorBody;
  files[`${OUT_DIR}/components/responses/errors.yaml`] = yaml(
    Object.fromEntries(
      Object.values(ERROR_RESPONSES).map(({ name, description }) => [
        name,
        { description, content: { 'application/json': { schema: errorSchemaRef } } },
      ])
    )
  );
  const { Error: errorSchema, PaginationMeta: paginationMeta, ...common } = shared;
  files[`${OUT_DIR}/components/schemas/error.yaml`] = yaml({ Error: errorSchema }, 'src/lib/contracts/common.ts');
  files[`${OUT_DIR}/components/schemas/pagination.yaml`] = yaml(
    { PaginationMeta: paginationMeta },
    'src/lib/contracts/common.ts'
  );
  files[`${OUT_DIR}/components/schemas/common.yaml`] = yaml(
    Object.fromEntries(Object.entries(common).sort(([a], [b]) => a.localeCompare(b))),
    'src/lib/contracts/common.ts'
  );

  files[`${OUT_DIR}/openapi.yaml`] = yaml({
    openapi: '3.1.0',
    info: {
      title: TITLE,
      version: VERSION,
      description:
        'Describes the API as it behaves today. Responses are `{ success: true, data }` (except the health probe); ' +
        'errors are `{ success: false, error, code? }` with a Vietnamese message.',
    },
    servers: [{ url: '/' }],
    security: [{ cookieAuth: [] }, { bearerAuth: [] }],
    tags,
    paths: rootPaths,
    components: {
      securitySchemes: {
        cookieAuth: { type: 'apiKey', in: 'cookie', name: 'auth_token' },
        bearerAuth: { type: 'http', scheme: 'bearer', bearerFormat: 'JWT' },
      },
    },
  });

  files[`${OUT_DIR}/README.md`] = readme();
  return files;
}

function readme(): string {
  const total = domains.reduce((sum, domain) => sum + domain.contracts.length, 0);
  const lines = [
    `<!-- ${GENERATED} -->`,
    '# API contract (OpenAPI)',
    '',
    `The contract of all ${total} API endpoints, describing the API as it behaves today. The files here are generated from ` +
      'the Zod contracts in `src/lib/contracts` (one module per domain), so the TypeScript code and this description cannot drift apart.',
    '',
    '## Layout',
    '',
    '| Path | Content |',
    '|---|---|',
    '| `openapi.yaml` | Entry point: info, security schemes, and one `$ref` per path into the domain files |',
    '| `<domain>.yaml` | Paths, parameters, request and response schemas of one domain |',
    '| `components/schemas/common.yaml` | Records shared by several domains (customer, product, order) |',
    '| `components/schemas/error.yaml` | The error body |',
    '| `components/schemas/pagination.yaml` | `PaginationMeta`, the metadata of paginated lists |',
    '| `components/responses/errors.yaml` | Shared error responses (400, 401, 403, …) |',
    '| `fixtures/responses/success/` | A real success response per endpoint, recorded from a seeded test server |',
    '| `fixtures/responses/empty/` | Real responses of list endpoints with no data |',
    '| `fixtures/responses/error/` | Real error responses |',
    '',
    '## Working with it',
    '',
    '- **Change or add an endpoint**: edit its contract in `src/lib/contracts/<domain>.ts`, then run `npm run contract:docs`.',
    '- **Add a domain**: create `src/lib/contracts/<domain>.ts` and add one entry to `domains` in `src/lib/contracts/index.ts`; its YAML file is generated.',
    '- **Check a running server**: `npm run contract:verify` calls every endpoint of a local seeded server and validates the real responses against the contracts. CI runs it against the built app.',
    '- **Refresh the fixtures**: `npm run contract:verify -- --record`.',
    '- The test suite fails when these files are stale, when a route has no contract, or when a fixture no longer matches its contract.',
    '',
    '## Conventions',
    '',
    '- **Authentication**: the httpOnly cookie `auth_token`, or `Authorization: Bearer <JWT>`. Both carry the same 7-day JWT.',
    '- **Success**: `{ "success": true, "data": … }`. The only exception is the health probe `/api/health`.',
    '- **Errors**: `{ "success": false, "error": "<Vietnamese message>", "code"?: "<CODE>" }`, from every endpoint, role guard and the middleware.',
    '- **Password change required**: an account flagged `mustChangePassword` gets `403` with `code: "PASSWORD_CHANGE_REQUIRED"` on every endpoint outside `/api/auth/*`.',
    '- **Pagination**: paginated lists take `?page=1&limit=20` (limit at most 200) and answer `{ "success": true, "data": [...], "meta": { "page", "limit", "total_item", "total_page" } }`.',
    '- **Dates**: timestamps are ISO 8601 strings; calendar dates are `YYYY-MM-DD`; months are `YYYY-MM`.',
    '- **Money**: always numbers (VND).',
    `- **Resent writes**: writes that add to a balance (payment, shells, production batch) accept an optional \`${IDEMPOTENCY_HEADER}\` header, one value per submission reused on resend. A resend is not written again and gets the first answer; the same key with a different request gets \`422\` with \`code: "IDEMPOTENCY_KEY_REUSED"\`.`,
    '',
    '## Endpoints',
    '',
  ];
  for (const domain of domains) {
    lines.push(`### [${domain.file}.yaml](${domain.file}.yaml)`, '', `${domain.description}.`, '');
    lines.push('| Method | Path | Access | Summary |', '|---|---|---|---|');
    for (const contract of domain.contracts) {
      const access = contract.auth.kind === 'custom' ? 'See the file' : describeAuth(contract.auth);
      lines.push(`| ${contract.method} | \`${contract.path}\` | ${access} | ${contract.summary} |`);
    }
    lines.push('');
  }
  return lines.join('\n').trimEnd() + '\n';
}

if (require.main === module) {
  const check = process.argv.includes('--check');
  let stale = false;
  for (const [path, content] of Object.entries(renderAll())) {
    if (check) {
      let current = '';
      try {
        current = readFileSync(path, 'utf8');
      } catch {
        current = '';
      }
      if (current !== content) {
        console.error(`✖ ${path} is out of date. Run: npm run contract:docs`);
        stale = true;
      }
    } else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content);
    }
  }
  if (stale) process.exit(1);
  if (!check) console.warn(`wrote ${Object.keys(renderAll()).length} files to ${OUT_DIR}/`);
}
